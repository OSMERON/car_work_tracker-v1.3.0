const bands: Array<[number, number]> = [
  [60,21.5],[70,23],[80,26],[90,29.5],[100,32],[110,34.5],[120,36.5],[130,38],
  [140,40],[150,42.5],[160,46],[170,48],[180,50],[190,51.5],[200,53.5],[210,56.5],
  [220,58],[230,60.5],[240,62],[250,63.5],[260,66],[270,68],[280,70.5],[290,73],
  [300,75],[350,85],[400,100],[450,120],[500,140],[550,160],[600,175]
];
export const tariffForMiles = (miles: number | null | undefined) => {
  if (miles == null || Number.isNaN(miles)) return 0;
  const band = bands.find(([max]) => miles <= max);
  return band?.[1] ?? 175;
};
